# out at run time (Sin::init, Exp2::init, Freqlut::init, Lfo::init/reset, PitchEnv::init, Env::init_sr, Porta::init_sr and
# Dx7Note::osc_freq's fine term), so they can live in the flash as const arrays.
import math
import sys

SR = 44118.0
N = 64
out = []


def arr(name, ctype, vals):
    out.append(f"static const {ctype} {name}[{len(vals)}] = {{")
    for i in range(0, len(vals), 8):
        out.append("  " + ", ".join(str(v) for v in vals[i:i + 8]) + ",")
    out.append("};")


def i32(v):
    v &= 0xFFFFFFFF
    return v - (1 << 32) if v >> 31 else v


# Sin::init (SIN_DELTA): a rotation in Q30
NS = 1024
d = 2 * math.pi / NS
c = int(math.floor(math.cos(d) * (1 << 30) + 0.5))
s = int(math.floor(math.sin(d) * (1 << 30) + 0.5))
u, v = 1 << 30, 0
R = 1 << 29
sintab = [0] * (NS * 2)
for i in range(NS // 2):
    sintab[(i << 1) + 1] = (v + 32) >> 6
    sintab[((i + NS // 2) << 1) + 1] = -((v + 32) >> 6)
    t = (u * s + v * c + R) >> 30
    u = (u * c - v * s + R) >> 30
    v = t
for i in range(NS - 1):
    sintab[i << 1] = sintab[(i << 1) + 3] - sintab[(i << 1) + 1]
sintab[(NS << 1) - 2] = -sintab[(NS << 1) - 1]

# Exp2::init
exp2tab = [0] * (NS * 2)
inc = 2 ** (1.0 / NS)
y = float(1 << 30)
for i in range(NS):
    exp2tab[(i << 1) + 1] = int(math.floor(y + 0.5))
    y *= inc
for i in range(NS - 1):
    exp2tab[i << 1] = exp2tab[(i << 1) + 3] - exp2tab[(i << 1) + 1]
exp2tab[(NS << 1) - 2] = i32((1 << 31) - exp2tab[(NS << 1) - 1])

# Freqlut::init
lut = []
y = (1 << 44) / SR
inc = math.pow(2, 1.0 / 1024)
for i in range(1025):
    lut.append(int(math.floor(y + 0.5)))
    y *= inc


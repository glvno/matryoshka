out.append('extern "C" const uint32_t msfa_lfo_delta[100];')
out.append('extern "C" const int32_t msfa_porta_rates[128], msfa_porta_gliss[128], msfa_fine[100];')
out.append(f"#define MSFA_LFO_UNIT {lfo_unit}u")
out.append(f"#define MSFA_PITCHENV_UNIT {pitchenv_unit}")
out.append(f"#define MSFA_ENV_SRMUL {env_srmul}u")
open(sys.argv[1] if len(sys.argv) > 1 else "msfa_tables.h", "w").write("\n".join(out) + "\n")

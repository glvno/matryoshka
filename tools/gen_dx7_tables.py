"""The DX7 module's rate-dependent tables (firmware/src/dx7.h) -> firmware/src/dx7_tables.h.

  tools/gen_dx7_tables.py [OUT]

msfa (Dexed Source/msfa at c314161a) works these out at start-up for its sample rate (Lfo::init / reset,
PitchEnv::init, Env::init_sr, Dx7Note::osc_freq's fine term); the FM-1 runs at one rate, 44,118 Hz, so they are const.
web/src/dx7.ts works out the same numbers for the browser's rate with the same formulas (dx7.test.ts: equal at 44,118 Hz).
The sine, exp2 and frequency tables are the firmware's own (dsp_tables.h SIN_T, EXP2_T).
"""
import math
import sys
from pathlib import Path

OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[1] / "firmware" / "src" / "dx7_tables.h"

SR = 44118.0
N = 64

# Lfo::init / reset: delta_ = lfoSource[rate] * lforatio_ (Hz of each LFO speed)
LFO_SOURCE = [
    0.062541, 0.125031, 0.312393, 0.437120, 0.624610, 0.750694, 0.936330, 1.125302, 1.249609, 1.436782,
    1.560915, 1.752081, 1.875117, 2.062494, 2.247191, 2.374451, 2.560492, 2.686728, 2.873976, 2.998950,
    3.188013, 3.369840, 3.500175, 3.682224, 3.812065, 4.000800, 4.186202, 4.310716, 4.501260, 4.623209,
    4.814636, 4.930480, 5.121901, 5.315191, 5.434783, 5.617346, 5.750431, 5.946717, 6.062811, 6.248438,
    6.431695, 6.564264, 6.749460, 6.868132, 7.052186, 7.250580, 7.375719, 7.556294, 7.687577, 7.877738,
    7.993605, 8.181967, 8.372405, 8.504848, 8.685079, 8.810573, 8.986341, 9.122423, 9.300595, 9.500285,
    9.607994, 9.798158, 9.950249, 10.117361, 11.251125, 11.384335, 12.562814, 13.676149, 13.904338, 15.092062,
    16.366612, 16.638935, 17.869907, 19.193858, 19.425019, 20.833333, 21.034918, 22.502250, 24.003841, 24.260068,
    25.746653, 27.173913, 27.578599, 29.052876, 30.693677, 31.191516, 32.658393, 34.317090, 34.674064, 36.416606,
    38.197097, 38.550501, 40.387722, 40.749796, 42.625746, 44.326241, 44.883303, 46.772685, 48.590865, 49.261084]

lforatio = int(4437500000.0 * N / SR) & 0xFFFFFFFF
lfo_delta = [int(x * lforatio) & 0xFFFFFFFF for x in LFO_SOURCE]
lfo_unit = int(N * 25190424 / SR + 0.5)
pitchenv_unit = int(N * (1 << 24) / (21.3 * SR) + 0.5)
env_srmul = int((44100.0 / SR) * (1 << 24))
freq_c = round(2 ** 44 / SR)        # Freqlut: msfa's table is 2^(i / 1024) times 2^44 / SR, so EXP2_T times this gives it
# osc_freq's fine term: (1 << 24) / log(2) * log(1 + fine / 100)
fine = [int(math.floor(24204406.323123 * math.log(1 + 0.01 * f) + 0.5)) for f in range(100)]


def arr(name, ctype, vals):
    lines = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), 8):
        lines.append("    " + ", ".join(str(v) for v in vals[i:i + 8]) + ",")
    lines.append("};")
    return "\n".join(lines)


OUT.write_text("\n".join([
    "/* SPDX-License-Identifier: Apache-2.0 */",
    "/* Generated by tools/gen_dx7_tables.py (msfa's start-up tables for 44,118 Hz). Do not edit. */",
    f"#define DX7_LFO_UNIT {lfo_unit}u",
    f"#define DX7_PITCHENV_UNIT {pitchenv_unit}",
    f"#define DX7_ENV_SRMUL {env_srmul}",
    f"#define DX7_FREQ_C {freq_c}u",
    arr("DX7_LFO_DELTA", "uint32_t", lfo_delta),
    arr("DX7_FINE", "int32_t", fine),
    "",
]))

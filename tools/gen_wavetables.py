# The wavetables of the `wavetable` module: banks of eight frames, each frame a band-limited single cycle given by
# its first 32 harmonics. Writes
#   firmware/src/wt_tables.h   int16 (Q15) tables, 257 samples (one guard) per frame, at three mip levels (32, 16, 8 harmonics)
#   web/src/wavetables.json    the harmonics (cos, sin coefficients) per frame; modules.ts builds the same tables from them
# Run from the repo root:  python3 tools/gen_wavetables.py
import json, math, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
NH = 32          # harmonics kept
N = 256          # samples per cycle
MIPS = [32, 16, 8]
FRAMES = 8

def dft(f, nh=NH, res=4096):
    """cos / sin coefficients of harmonics 1..nh of the periodic function f(t), t in [0, 1)"""
    xs = [f(i / res) for i in range(res)]
    out = []
    for k in range(1, nh + 1):
        c = sum(x * math.cos(2 * math.pi * k * i / res) for i, x in enumerate(xs)) * 2 / res
        s = sum(x * math.sin(2 * math.pi * k * i / res) for i, x in enumerate(xs)) * 2 / res
        out.append((c, s))
    return out

def harm(amps):
    """a frame from harmonic amplitudes {k: a} (sines)"""
    return [(0.0, amps.get(k, 0.0)) for k in range(1, NH + 1)]

def mix(a, b, t):
    return [(x[0] * (1 - t) + y[0] * t, x[1] * (1 - t) + y[1] * t) for x, y in zip(a, b)]

def synth(coef, nh, n=N):
    return [sum(c * math.cos(2 * math.pi * k * i / n) + s * math.sin(2 * math.pi * k * i / n) for k, (c, s) in enumerate(coef[:nh], 1)) for i in range(n)]

def normalize(coef):
    peak = max(abs(v) for v in synth(coef, NH, 2048))
    return [(c / peak, s / peak) for c, s in coef]

sine = lambda t: math.sin(2 * math.pi * t)
tri = lambda t: 4 * abs(t - math.floor(t + 0.5)) - 1
saw = lambda t: 2 * t - 1
def pulse(d):
    return lambda t: 1.0 if t < d else -1.0

# bank 0 "analog": sine .. triangle .. saw .. square .. narrow pulses
SINE, TRI, SAW, SQ = dft(sine), dft(tri), dft(saw), dft(pulse(0.5))
analog = [SINE, TRI, mix(TRI, SAW, 0.5), SAW, mix(SAW, SQ, 0.5), SQ, dft(pulse(0.25)), dft(pulse(0.1))]

# bank 1 "organ": drawbar-like harmonic sets
organ = [
    harm({1: 1}),
    harm({1: 1, 2: 0.7}),
    harm({1: 1, 3: 0.6}),
    harm({1: 1, 2: 0.8, 3: 0.6, 4: 0.5}),
    harm({1: 0.8, 2: 1, 4: 0.6, 8: 0.4}),
    harm({1: 1, 3: 0.8, 5: 0.6, 7: 0.4}),
    harm({k: 1 / math.sqrt(k) for k in range(1, 9)}),
    harm({1: 1, 6: 0.6, 8: 0.5, 12: 0.4}),
]

# bank 2 "formant": a bump of harmonics that moves up the series, the fundamental always present
def formant(i):
    c = 1.5 + i * 2.2
    w = 1 + i * 0.4
    return harm({k: math.exp(-((k - c) / w) ** 2 / 2) + (0.3 if k == 1 else 0) for k in range(1, NH + 1)})
form = [formant(i) for i in range(FRAMES)]

# bank 3 "digital": shapes with steps and corners
def stair(levels):
    return lambda t: (math.floor((math.sin(2 * math.pi * t) * 0.999 + 1) / 2 * levels) + 0.5) / levels * 2 - 1
half = lambda t: max(0.0, math.sin(2 * math.pi * t)) * 2 - 1
trap = lambda t: max(-1.0, min(1.0, 3 * tri(t)))
synced = lambda t: math.sin(2 * math.pi * ((t * 2.5) % 1))
full = lambda t: abs(math.sin(2 * math.pi * t)) * 2 - 1
cubed = lambda t: math.sin(2 * math.pi * t) ** 3
notch = lambda t: saw(t) if t < 0.5 else -saw(t)
digital = [dft(stair(4)), dft(stair(8)), dft(half), dft(trap), dft(synced), dft(full), dft(cubed), dft(notch)]

# bank 4 "eml color": EML 101 owner's manual pp. 9-10, plus the service notes' "double saw" endpoint.
# Triangle -> sloped square -> square -> saw -> double saw (one octave up, no fundamental).
# The intermediate knob positions are our interpolation, not a measured calibration of the original pot.
SLOPE = mix(TRI, SQ, 0.5)
DOUBLE_SAW = dft(lambda t: saw((2 * t) % 1))
eml_color = [TRI, mix(TRI, SLOPE, 0.5), SLOPE, SQ, mix(SQ, SAW, 0.5), SAW, mix(SAW, DOUBLE_SAW, 0.5), DOUBLE_SAW]

BANKS = [('analog', analog), ('organ', organ), ('formant', form), ('digital', digital), ('eml color', eml_color)]
frames = [normalize(f) for _, bank in BANKS for f in bank]

# the JSON for the reference engine
js = {'banks': [n for n, _ in BANKS], 'frames': [[[round(c, 7), round(s, 7)] for c, s in f] for f in frames]}
(ROOT / 'web/src/wavetables.json').write_text(json.dumps(js, separators=(',', ':')) + '\n')

# the C tables, from the rounded coefficients (so both engines start from the same numbers)
L = ['/* SPDX-License-Identifier: GPL-3.0-only */', '/* Generated by tools/gen_wavetables.py. Do not edit. */', '#pragma once', '#include <stdint.h>',
     f'#define WT_N {N}', f'#define WT_FRAMES {len(frames)}', f'#define WT_MIPS {len(MIPS)}',
     '/* [mip][frame][sample]: mip 0 = 32 harmonics, 1 = 16, 2 = 8; Q15; sample 256 repeats sample 0 for the interpolation */',
     f'static const int16_t WT_T[WT_MIPS][WT_FRAMES][WT_N + 1] = {{']
for nh in MIPS:
    L.append('  {')
    for f in js['frames']:
        ys = synth([(c, s) for c, s in f], nh)
        ys.append(ys[0])
        q = [max(-32768, min(32767, round(y * 32767))) for y in ys]
        rows = [', '.join(str(v) for v in q[i:i + 16]) for i in range(0, len(q), 16)]
        L.append('    {' + ',\n     '.join(rows) + '},')
    L.append('  },')
L.append('};')
(ROOT / 'firmware/src/wt_tables.h').write_text('\n'.join(L) + '\n')
print(f'wrote {len(frames)} frames x {len(MIPS)} mips')

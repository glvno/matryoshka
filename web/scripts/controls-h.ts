// firmware/src/controls.h from web/src/controls.ts (#553): the controls sheet's lines per state and tab, the conditions
// (help_ui.c hc_<name>), the pages' hint lines, and for firmware/test/controls_test.h each row's gesture and effect.
// Checked here: each line fits the sheet's card (help_ui.c help_row's layout in FONT_S), each hint line its field, each
// condition is a function in help_ui.c, no tab holds more lines than the sheet takes (HC_ROWS).
import { BUTTON_ID, CONDITIONS, CONTROLS, EFFECTS, ENCODER_ID, HELP_STATES, HELP_STATE_NAME, HINT_ROWS, HINTS, hintText, LIST_MARK, PATCH_BUTTONS, README_END, README_START, readmeControls, rowSpec, sheetRows, type ControlRow, type Part } from '../src/controls';

/** FONT_S's advance per ASCII character (firmware/src/font_bc.h font_s_g, map 0x20.. in order) */
export function fontAdvances(fontH: string): number[] {
  const body = /font_s_g\[95\] = \{([\s\S]*?)\n\};/.exec(fontH)?.[1];
  if (!body) throw new Error('controls: font_s_g not found in font_bc.h');
  const adv = [...body.matchAll(/\{(-?\d+), (-?\d+), (-?\d+), (\d+)\}/g)].map((m) => Number(m[2]));
  if (adv.length !== 95) throw new Error(`controls: font_s_g has ${adv.length} glyphs, not 95`);
  return adv;
}

/** help_ui.c help_row's layout: where a line's parts end, and its right edge with the description (HC_X0 24, the
 * description column 124, 4 px between parts) */
export function lineWidth(spec: string, adv: number[]): { parts: number; right: number } {
  const tw = (s: string): number => [...s].reduce((w, c) => w + (adv[c.charCodeAt(0) - 32] ?? 0), 0);
  const [head, desc] = spec.includes('~') ? [spec.slice(0, spec.indexOf('~')), spec.slice(spec.indexOf('~') + 1)] : [spec, undefined];
  let x = 24;
  for (const p of head.split('|')) {
    const t = p.slice(2, 33);
    const w = p[0] === 'k' ? tw(t) + 8 : p[0] === 'n' ? 20 + tw(t) : p[0] === 'c' ? t.length * 17 - 1 : p[0] === 'w' ? 11 + tw('WHITE')
      : p[0] === 'b' ? 11 + tw('BLACK') + (t ? tw(' ') + tw(t) : 0) : tw(t);
    x += w + 4;
  }
  return { parts: x, right: desc === undefined ? x : (x > 124 ? x + 2 : 124) + tw(desc) };
}

const C_ROWS = 24;          // help_ui.c HC_ROWS: the most lines a tab holds
const RIGHT = 222;          // a line's last pixel column (the card's inside, help_row's text field)
const PATCH_ROWS = 4;       // help_patch_rows: at most four
const PAGE_BUTTONS = ['FX', 'LFO', 'EDIT', 'ARP'];   // the buttons a Page button's list can be on (help_ui.c help_fill names one)

const cname = (s: string): string => s.toUpperCase().replace(/[^A-Z0-9]/g, '_');

export function controlsHeader(helpUi: string, fontH: string): string {
  const adv = fontAdvances(fontH);
  for (const c of CONDITIONS)
    if (!new RegExp(`static int hc_${c}\\(void\\)`).test(helpUi)) throw new Error(`controls: the condition ${c} has no hc_${c}(void) in help_ui.c`);
  const ids = new Set<string>();
  for (const r of CONTROLS) {
    if (ids.has(r.id)) throw new Error(`controls: two rows named ${r.id}`);
    ids.add(r.id);
    if (!r.sheet && !r.everywhere) throw new Error(`controls: ${r.id} shows nowhere`);
    if (r.gesture.where && r.gesture.where !== 'on END') throw new Error(`controls: ${r.id}: where "${r.gesture.where}" is not known to controls_test.h`);
    // (`{list}`: checked with each patch button's name; help_fill puts a label that does not fit back to the name)
    const lines = [rowSpec(r), ...(r.heading ? [`t:${r.heading}`] : [])].flatMap((l) => (l.includes(LIST_MARK) ? PAGE_BUTTONS.map((b) => l.replace(LIST_MARK, b)) : [l]));
    if (r.does.split(LIST_MARK).length > 2) throw new Error(`controls: ${r.id}: more than one ${LIST_MARK}`);
    for (const line of lines) {
      const w = lineWidth(line, adv);
      if (w.right > RIGHT) throw new Error(`controls: ${r.id}: "${line}" is ${w.right - RIGHT} px wider than the sheet`);
    }
  }
  const L: string[] = [];
  const w = (s = ''): number => L.push(s);
  w('/* SPDX-License-Identifier: GPL-3.0-only */');
  w('/* Generated by web/scripts/export-defs.ts from web/src/controls.ts (#553). Do not edit: change the table there. */');
  w('#pragma once');
  w('#include <stdint.h>');
  w();
  w('/* the states (D-245): the sheet\'s first tab is named after the one the FM-1 is in (help_ui.c help_state) */');
  w(`enum { ${HELP_STATES.map((s) => `HS_${cname(s)}`).join(', ')}, HS_COUNT };`);
  w(`static const char *const HS_NAME[HS_COUNT] = {${HELP_STATES.map((s) => `"${HELP_STATE_NAME[s]}"`).join(', ')}};`);
  w();
  w('/* the conditions a line shows under: help_ui.c hc_<name> */');
  for (const c of CONDITIONS) w(`static int hc_${c}(void);`);
  w(`enum { HC_NONE, ${CONDITIONS.map((c) => `HC_${cname(c)}`).join(', ')}, HC_COUNT };`);
  w(`static int (*const HC_FN[HC_COUNT])(void) = {0, ${CONDITIONS.map((c) => `hc_${c}`).join(', ')}};`);
  w();
  // the lines: a row's heading, then the row; the patch buttons' place
  type Line = { spec: string | null; row: number; cond: number; neg: number };
  const lines: Line[] = [];
  const lineOf = new Map<string, number[]>();
  const condOf = (r: ControlRow): { cond: number; neg: number } => {
    if (!r.when) return { cond: 0, neg: 0 };
    const neg = r.when.startsWith('!');
    return { cond: CONDITIONS.indexOf(r.when.replace('!', '') as (typeof CONDITIONS)[number]) + 1, neg: neg ? 1 : 0 };
  };
  CONTROLS.forEach((r, i) => {
    const c = condOf(r), at: number[] = [];
    if (r.heading) at.push(lines.push({ spec: `t:${r.heading}`, row: i, ...c }) - 1);
    at.push(lines.push({ spec: rowSpec(r), row: i, ...c }) - 1);
    lineOf.set(r.id, at);
  });
  lineOf.set(PATCH_BUTTONS.id, [lines.push({ spec: null, row: 255, cond: 0, neg: 0 }) - 1]);
  if (lines.length >= 255) throw new Error('controls: more than 254 lines');
  w('/* a line of the sheet: its spec (help_ui.c help_part), the row it belongs to (CTL_ROW; CTL_PATCH: no spec, the patch');
  w(' * buttons go here), shown when HC_FN[cond]() is not neg */');
  w('typedef struct { const char *spec; uint8_t row, cond, neg; } ctl_line_t;');
  w('#define CTL_PATCH 255u');
  w(`static const ctl_line_t CTL_LINE[${lines.length}] = {`);
  for (const l of lines) w(`    {${l.spec === null ? '0' : JSON.stringify(l.spec)}, ${l.row === 255 ? 'CTL_PATCH' : l.row}, ${l.cond}, ${l.neg}},${l.row === 255 ? '' : `   /* ${CONTROLS[l.row].id} */`}`);
  w('};');
  // the tabs: per state (HS_* order) its own tab, then its EVERYWHERE tab
  const tabs = (['state', 'everywhere'] as const).map((tab) => HELP_STATES.map((s) => {
    const rows = sheetRows(s, tab);
    const at = rows.flatMap((r) => lineOf.get(r.id)!);
    const most = at.length + (rows.includes(PATCH_BUTTONS) ? PATCH_ROWS - 1 : 0);
    if (most > C_ROWS) throw new Error(`controls: ${s}'s ${tab} tab can hold ${most} lines, more than the sheet's ${C_ROWS}`);
    return at;
  }));
  const max = Math.max(...tabs.flat().map((t) => t.length)) + 1;
  w();
  w('/* the lines of each tab in order, CTL_END after the last: [0] the state\'s tab, [1] EVERYWHERE; per state in HS_* order */');
  w('#define CTL_END 255u');
  w(`static const uint8_t CTL_SHEET[2][${HELP_STATES.length}][${max}] = {`);
  tabs.forEach((states) => {
    w('    {');
    states.forEach((at, i) => w(`        {${[...at, 'CTL_END'].join(', ')}},   /* ${HELP_STATES[i]} */`));
    w('    },');
  });
  w('};');
  // the hint lines (FONT_S, each within its field)
  const tw = (t: string): number => [...t].reduce((n, c) => n + (adv[c.charCodeAt(0) - 32] ?? 0), 0);
  w();
  w('/* the pages\' hint lines, in the rows\' words (controls.ts HINTS): the text and the field it fits */');
  for (const h of HINTS) {
    const t = hintText(h);
    if (tw(t) > h.width) throw new Error(`controls: the hint ${h.id} "${t}" is ${tw(t) - h.width} px wider than its ${h.width}`);
    w(`#define HINT_${cname(h.id)} ${JSON.stringify(t)}   /* ${tw(t)} of ${h.width} px */`);
  }
  for (const id of HINT_ROWS) {
    const t = CONTROLS.find((r) => r.id === id)?.hint;
    if (!t) throw new Error(`controls: HINT_ROWS: ${id} has no hint`);
    w(`#define HINT_ROW_${cname(id)} ${JSON.stringify(t)}`);
  }
  // the gestures and effects, for the test
  w();
  w('#ifdef CTL_GESTURES');
  w('/* what each row does (firmware/test/controls_test.h checks it) */');
  w(`enum { ${EFFECTS.map((e) => `CE_${cname(e)}`).join(', ')}, CE_COUNT };`);
  w('/* a gesture part: a button (id: its matrix id), an encoder (id: panel_encoders\' index), K1..K4 (id: a mask, bit 0 K1), a');
  w(' * white key, a black key (n: black key n, 0 any), any key, the keys played, keys together */');
  w('enum { CK_BUTTON, CK_ENCODER, CK_KNOBS, CK_WHITE, CK_BLACK, CK_ANY, CK_KEYS, CK_CHORD };');
  w('#define CH_NONE 255u                       /* hold: nothing held; CH_STEP a step (its white key) held; else a matrix id */');
  w('#define CH_STEP 254u');
  w('enum { CW_PRESS, CW_TAP, CW_HELD, CW_HOLD2S };   /* how: as the handler takes it, a tap, held while keys play, held 2 s */');
  w('typedef struct { uint8_t kind, id, n; } ctl_part_t;');
  w('typedef struct { const char *id; uint8_t effect, hold, how, at_end, nalt; ctl_part_t alt[5]; } ctl_row_t;');
  const part = (p: Part): string => {
    if ('button' in p) return `{CK_BUTTON, ${BUTTON_ID[p.button]}, 0}`;
    if ('encoder' in p) return `{CK_ENCODER, ${ENCODER_ID[p.encoder]}, 0}`;
    if ('knobs' in p) return `{CK_KNOBS, ${[...p.knobs].reduce((m, d) => m | 1 << (Number(d) - 1), 0)}, 0}`;
    return `{CK_${p.key === 'white' ? 'WHITE' : p.key === 'black' ? 'BLACK' : p.key === 'any' ? 'ANY' : p.key === 'keys' ? 'KEYS' : 'CHORD'}, 0, ${p.n ?? 0}}`;
  };
  w(`#define CTL_NROWS ${CONTROLS.length}`);
  w('static const ctl_row_t CTL_ROW[CTL_NROWS] = {');
  for (const r of CONTROLS) {
    const g = r.gesture;
    const hold = g.hold === undefined ? 'CH_NONE' : g.hold === 'step' ? 'CH_STEP' : String(BUTTON_ID[g.hold]);
    const how = g.how === 'tap' ? 'CW_TAP' : g.how === 'held' ? 'CW_HELD' : g.how === 'hold 2 s' ? 'CW_HOLD2S' : 'CW_PRESS';
    if (g.do.length > 5) throw new Error(`controls: ${r.id}: more than 5 parts`);
    w(`    {"${r.id}", CE_${cname(r.effect)}, ${hold}, ${how}, ${g.where ? 1 : 0}, ${g.do.length}, {${g.do.map(part).join(', ')}}},`);
  }
  w('};');
  w('#endif');
  w();
  return L.join('\n');
}

/** the README with its list of controls made again from the table (between README_START and README_END) */
export function readmeWithControls(readme: string): string {
  const a = readme.indexOf(README_START), b = readme.indexOf(README_END);
  if (a < 0 || b < a) throw new Error('controls: README.md has no controls markers');
  return readme.slice(0, a) + readmeControls() + readme.slice(b + README_END.length);
}
